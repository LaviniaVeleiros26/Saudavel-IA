begin;

create table if not exists public.respostas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null default auth.uid() references auth.users(id),
  entrada text not null,
  resposta text not null
);

-- Add only missing columns, preserving an existing table and its records.
alter table public.respostas
  add column if not exists id bigint generated by default as identity,
  add column if not exists created_at timestamptz default now(),
  add column if not exists user_id uuid default auth.uid() references auth.users(id),
  add column if not exists entrada text,
  add column if not exists resposta text;

alter table public.respostas enable row level security;
grant select, insert on public.respostas to authenticated;

-- Allow identity-backed IDs for authenticated inserts, including existing serial IDs.
do $$
declare id_sequence text;
begin
  id_sequence := pg_get_serial_sequence('public.respostas', 'id');
  if id_sequence is not null then
    execute format('grant usage on sequence %s to authenticated', id_sequence);
  end if;
end $$;

drop policy if exists respostas_ler_proprias on public.respostas;
create policy respostas_ler_proprias on public.respostas
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists respostas_salvar_proprias on public.respostas;
create policy respostas_salvar_proprias on public.respostas
  for insert to authenticated with check ((select auth.uid()) = user_id);

-- Restrictive guard also limits any pre-existing permissive policies.
drop policy if exists respostas_apenas_dono on public.respostas;
create policy respostas_apenas_dono on public.respostas as restrictive
  for all to public
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create index if not exists respostas_user_created_idx
  on public.respostas (user_id, created_at desc, id desc);

commit;
